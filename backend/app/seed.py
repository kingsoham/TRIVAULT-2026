def seed_demo_data() -> None:
    """
    Seed the database with demo users and demo files.
    Idempotent: skips seeding if any user already exists.
    Only runs when APP_ENV=development.
    """
    from app.config import get_settings

    settings = get_settings()

    # Guard: never seed in production or testing environments
    if settings.APP_ENV.lower() not in ("development", "dev"):
        logger.debug("Seeding skipped: APP_ENV=%s is not development.", settings.APP_ENV)
        return

    engine = get_engine()

    with Session(engine) as session:
        # Idempotency check — if ANY user row exists, skip entirely
        existing = session.exec(select(User).limit(1)).first()
        if existing:
            logger.info(
                "Demo seed skipped: database already contains user '%s'.",
                existing.username,
            )
            return

        logger.info("🌱 Seeding TriVault demo data ...")

        created_users: list[User] = []

        for user_def in DEMO_USERS:
            user = User(
                username=user_def["username"],
                email=user_def["email"],
                password_hash=get_password_hash(user_def["password"]),
                created_at=datetime.now(timezone.utc),
            )
            session.add(user)
            session.flush()  # Get auto-assigned user.id before committing
            created_users.append(user)
            logger.info("  ✅ Created user: %s  (%s)", user.username, user.email)

        # Commit users so their IDs are stable
        session.commit()

        # Refresh to read back IDs
        for user in created_users:
            session.refresh(user)

        # Seed demo files for each user
        for user in created_users:
            for file_def in DEMO_FILES_PER_USER:
                file_bytes = file_def["content"].encode("utf-8")

                try:
                    storage_id, _manifest = FileService.process_and_store_file(
                        file_bytes=file_bytes,
                        original_filename=file_def["filename"],
                    )

                    stored = StoredFile(
                        filename=file_def["filename"],
                        storage_id=storage_id,
                        size=len(file_bytes),
                        user_id=user.id,
                        content_type=file_def["content_type"],
                        created_at=datetime.now(timezone.utc),
                        shard_count=3,
                    )
                    session.add(stored)
                    logger.info(
                        "    📄 Added file '%s' for user '%s' (storage_id=%s)",
                        file_def["filename"],
                        user.username,
                        storage_id,
                    )
                except Exception as exc:
                    logger.warning(
                        "    ⚠️  Could not seed file '%s' for '%s': %s",
                        file_def["filename"],
                        user.username,
                        exc,
                    )

        session.commit()

    _print_seed_summary()


